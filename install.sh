#!/usr/bin/env bash
# Vocab — one script for everything.
#   ./install.sh          setup: deps, fonts, .env, config, android project
#   ./install.sh admin    admin panel  → http://localhost:4321  (app preview: /app/)
#   ./install.sh apk      build debug APK + install on USB phone
#   ./install.sh release  signed APK → GitHub Releases → landing page (1.1 → 2.1 → 3.1 …)
#   ./install.sh config   regenerate www/js/config.js + capacitor.config.json from .env
set -euo pipefail
cd "$(dirname "$0")"
G='\033[0;32m'; Y='\033[0;33m'; R='\033[0;31m'; N='\033[0m'
ok(){ echo -e "${G}✓${N} $*"; }; warn(){ echo -e "${Y}!${N} $*"; }; die(){ echo -e "${R}✗${N} $*"; exit 1; }

need_node(){
  command -v node >/dev/null || die "Node 18+ required: https://nodejs.org"
  [ "$(node -p 'process.versions.node.split(".")[0]')" -ge 18 ] || die "Node 18+ required (found $(node -v))"
}

env_file(){
  [ -f .env ] || { cp .env.example .env; warn ".env created — fill SUPABASE_URL / SUPABASE_PUBLISHABLE_KEY / SUPABASE_SECRET_KEY"; }
  # GITHUB_RAW empty → derive from git remote
  if ! grep -qE '^GITHUB_RAW=.+' .env; then
    url="$(git remote get-url origin 2>/dev/null || true)"
    if [[ "$url" =~ github\.com[:/]([^/]+)/([^/.]+) ]]; then
      br="$(grep -E '^GIT_BRANCH=' .env | cut -d= -f2)"; br="${br:-main}"
      raw="https://raw.githubusercontent.com/${BASH_REMATCH[1]}/${BASH_REMATCH[2]}/${br}/data"
      sed -i "s|^GITHUB_RAW=.*|GITHUB_RAW=${raw}|" .env; ok "GITHUB_RAW=${raw}"
    else warn "no GitHub remote — set GITHUB_RAW in .env manually"; fi
  fi
}

config(){
  node - <<'JS'
const fs=require('fs');
const env=Object.fromEntries(fs.readFileSync('.env','utf8').split(/\r?\n/).map(l=>l.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/)).filter(Boolean).map(m=>[m[1],m[2].replace(/^["']|["']$/g,'')]));
const cfg={APP_NAME:env.APP_NAME||'Vocab',APP_ID:env.APP_ID||'com.vocab.app',FOLDER:env.FOLDER||'vocab',
  SUPABASE_URL:(env.SUPABASE_URL||'').replace(/\/$/,''),SUPABASE_ANON:env.SUPABASE_PUBLISHABLE_KEY||env.SUPABASE_ANON_KEY||'',BY_NAME:env.BY_NAME||env.APP_NAME||'Vocab',BY_URL:env.BY_URL||'https://t.me/odilxanivich',GITHUB_RAW:(env.GITHUB_RAW||'').replace(/\/$/,'')};
fs.writeFileSync('www/js/config.js','/* Generated by install.sh from .env — public values only */\nwindow.CFG='+JSON.stringify(cfg,null,1)+';\n');
fs.writeFileSync('capacitor.config.json',JSON.stringify({appId:cfg.APP_ID,appName:cfg.APP_NAME,webDir:'www',backgroundColor:'#050505',
  server:{androidScheme:'https'},android:{backgroundColor:'#050505'}},null,2)+'\n');
JS
  ok "www/js/config.js + capacitor.config.json"
}

fonts(){
  mkdir -p www/fonts
  p="$(find node_modules/pretendard -name 'PretendardVariable.woff2' 2>/dev/null | head -1)"
  i="$(find node_modules/@fontsource-variable/inter -name 'inter-cyrillic-wght-normal.woff2' 2>/dev/null | head -1)"
  [ -n "$p" ] && cp "$p" www/fonts/PretendardVariable.woff2 && ok "font: Pretendard (Hangul + Latin)" || warn "Pretendard not found"
  [ -n "$i" ] && cp "$i" www/fonts/inter-cyrillic.woff2 && ok "font: Inter (Cyrillic)" || warn "Inter not found"
}

android_ready(){ [ -n "${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}" ] || [ -d "$HOME/Android/Sdk" ]; }

patch_manifest(){
  APP_ID="$(node -p "require('./capacitor.config.json').appId")" python3 - <<'PY'
import os
p='android/app/src/main/AndroidManifest.xml'; s=open(p).read(); app=os.environ['APP_ID']
def perm(name,extra=''):
    global s
    if 'permission.'+name+'"' not in s:
        s=s.replace('<application','<uses-permission android:name="android.permission.%s"%s/>\n    <application'%(name,extra),1)
perm('READ_EXTERNAL_STORAGE',' android:maxSdkVersion="32"')
perm('WRITE_EXTERNAL_STORAGE',' android:maxSdkVersion="29"')
if 'requestLegacyExternalStorage' not in s:
    s=s.replace('<application','<application android:requestLegacyExternalStorage="true"',1)
if 'TTS_SERVICE' not in s:   # Android 11+: lets the app see TTS engines (Google TTS, Samsung…)
    s=s.replace('</manifest>','    <queries><intent><action android:name="android.intent.action.TTS_SERVICE"/></intent></queries>\n</manifest>',1)
if 'android:scheme="%s"'%app not in s:  # Google login comes back here: <APP_ID>://auth
    s=s.replace('</activity>','<intent-filter><action android:name="android.intent.action.VIEW"/><category android:name="android.intent.category.DEFAULT"/><category android:name="android.intent.category.BROWSABLE"/><data android:scheme="%s" android:host="auth"/></intent-filter>\n        </activity>'%app,1)
if 'screenOrientation' not in s:
    s=s.replace('<activity','<activity android:screenOrientation="portrait"',1)
open(p,'w').write(s)
PY
  ok "AndroidManifest: deep link, TTS, storage"
}

icons(){
  command -v convert >/dev/null || { warn "icons skipped (sudo apt install imagemagick)"; return; }
  local S=www/icon.png Rz=android/app/src/main/res
  [ -f "$S" ] || S=www/icon.svg
  [ -f "$S" ] || { warn "no www/icon.png — icons skipped"; return; }
  for pair in mdpi:48 hdpi:72 xhdpi:96 xxhdpi:144 xxxhdpi:192; do
    d=${pair%%:*}; s=${pair##*:}; f=$((s*108/48))
    mkdir -p "$Rz/mipmap-$d"
    convert -background none -density 384 "$S" -resize ${s}x${s} "$Rz/mipmap-$d/ic_launcher.png"
    cp "$Rz/mipmap-$d/ic_launcher.png" "$Rz/mipmap-$d/ic_launcher_round.png"
    convert -background none -density 384 "$S" -resize ${f}x${f}^ -gravity center -extent ${f}x${f} "$Rz/mipmap-$d/ic_launcher_foreground.png"
  done
  echo '<?xml version="1.0" encoding="utf-8"?><resources><color name="ic_launcher_background">#050505</color></resources>' > "$Rz/values/ic_launcher_background.xml"
  ok "icons"
}

android(){
  android_ready || { warn "No Android SDK — later: ./install.sh apk (needs JDK 17 + Android SDK)"; return; }
  [ -d android ] || npx cap add android
  npx cap sync android
  patch_manifest; icons
}

case "${1:-setup}" in
  setup)
    need_node; env_file
    npm install --no-audit --no-fund
    fonts; config; node admin/server.js --index; android
    echo; ok "Done."
    echo "  Admin + web preview : ./install.sh admin   → http://localhost:4321"
    echo "  APK                 : ./install.sh apk"
    ;;
  admin)  need_node; env_file; config; exec node admin/server.js ;;
  config) need_node; env_file; config ;;
  apk)
    need_node; env_file; config
    android_ready || die "Android SDK not found (set ANDROID_HOME)"
    command -v java >/dev/null || die "JDK 17 required: sudo apt install openjdk-17-jdk"
    [ -d node_modules ] || npm install --no-audit --no-fund
    [ -f www/fonts/PretendardVariable.woff2 ] || fonts
    android
    (cd android && ./gradlew assembleDebug)
    APK=android/app/build/outputs/apk/debug/app-debug.apk
    cp "$APK" ./vocab-debug.apk; ok "APK: ./vocab-debug.apk"
    if command -v adb >/dev/null && adb devices | grep -qw device; then adb install -r "$APK" && ok "Installed on phone"; else warn "No phone over USB — install the APK manually"; fi
    ;;
  release)
    # Signed APK → GitHub Release → landing/releases.json → push.  Usage: ./install.sh release [version]
    need_node; env_file; config
    android_ready || die "Android SDK not found (set ANDROID_HOME)"
    command -v java >/dev/null || die "JDK 17 required: sudo apt install openjdk-17-jdk"
    command -v gh >/dev/null || die "GitHub CLI required: sudo apt install gh && gh auth login"
    gh auth status >/dev/null 2>&1 || die "Run: gh auth login"
    [ -d node_modules ] || npm install --no-audit --no-fund
    KS=vocab-release.jks
    KP="$(grep -E '^KEYSTORE_PASS=' .env | cut -d= -f2- || true)"
    if [ ! -f "$KS" ]; then
      warn "Creating your signing key ($KS). BACK IT UP + the password — if lost, users can't update the app."
      read -rsp "New key password (6+ chars): " KP; echo
      [ ${#KP} -ge 6 ] || die "Password too short"
      keytool -genkeypair -keystore "$KS" -alias vocab -keyalg RSA -keysize 2048 -validity 10000 \
        -storepass "$KP" -keypass "$KP" -dname "CN=Vocab, O=Vocab" >/dev/null
      grep -q '^KEYSTORE_PASS=' .env && sed -i "s|^KEYSTORE_PASS=.*|KEYSTORE_PASS=$KP|" .env || echo "KEYSTORE_PASS=$KP" >> .env
      ok "Key created: $KS"
    fi
    [ -n "$KP" ] || { read -rsp "Key password: " KP; echo; }
    mkdir -p landing dist; [ -f landing/releases.json ] || echo '[]' > landing/releases.json
    PREV="$(node -p "(require('./landing/releases.json')[0]||{}).version||''")"
    CODE="$(node -p "((require('./landing/releases.json')[0]||{}).code||0)+1")"
    VER="${2:-$(node -p "'$PREV'?(parseInt('$PREV')+1)+'.1':'1.1'")}"
    git rev-parse -q --verify "refs/tags/v$VER" >/dev/null && die "v$VER already exists"
    echo "Releasing Vocab $VER (previous: ${PREV:-none})"
    read -rp "What's new (separate items with ;): " NOTES
    android
    sed -i -E "s/versionCode [0-9]+/versionCode $CODE/; s/versionName \"[^\"]*\"/versionName \"$VER\"/" android/app/build.gradle
    npx cap build android --keystorepath "$PWD/$KS" --keystorepass "$KP" --keystorealias vocab --keystorealiaspass "$KP" --androidreleasetype APK
    APK="$(ls -t android/app/build/outputs/apk/release/*.apk 2>/dev/null | grep -v unsigned | head -1)"
    [ -f "$APK" ] || die "Signed APK not found in android/app/build/outputs/apk/release/"
    OUT="dist/vocab-$VER.apk"; cp "$APK" "$OUT"
    SHA="$(sha256sum "$OUT" | cut -d' ' -f1)"; SIZE="$(stat -c%s "$OUT")"
    REPO="$(gh repo view --json nameWithOwner -q .nameWithOwner)"
    printf '%s\n' "$NOTES" | tr ';' '\n' | sed 's/^ *//;/^$/d;s/^/- /' > dist/notes.md
    printf '\nSHA-256: `%s`\n' "$SHA" >> dist/notes.md
    gh release create "v$VER" "$OUT" --title "Vocab $VER" --notes-file dist/notes.md
    VER="$VER" CODE="$CODE" SHA="$SHA" SIZE="$SIZE" NOTES="$NOTES" URL="https://github.com/$REPO/releases/download/v$VER/vocab-$VER.apk" node -e '
      const fs=require("fs"),f="landing/releases.json",r=JSON.parse(fs.readFileSync(f,"utf8")),e=process.env;
      r.unshift({version:e.VER,code:+e.CODE,date:new Date().toISOString(),size:+e.SIZE,sha256:e.SHA,url:e.URL,notes:e.NOTES.split(";").map(s=>s.trim()).filter(Boolean)});
      fs.writeFileSync(f,JSON.stringify(r,null,1)+"\n")'
    git add landing/releases.json && git commit -qm "release v$VER" && git push -q
    ok "Vocab $VER released · SHA-256 $SHA"
    echo "  Page updates in ~1 min. If an old debug build is on your phone, uninstall it once (different signature)."
    ;;
  *) die "Unknown command: $1  (setup | admin | apk | release | config)" ;;
esac